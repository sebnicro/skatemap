-- 1. Crear tabla de spots
DROP TABLE IF EXISTS skate_spots;

CREATE TABLE skate_spots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  categoria TEXT NOT NULL CHECK (categoria IN ('skatepark', 'spot', 'skateshop')),
  latitud DOUBLE PRECISION NOT NULL,
  longitud DOUBLE PRECISION NOT NULL,
  valor INTEGER DEFAULT 50 CHECK (valor >= 1 AND valor <= 100), -- Nivel de dificultad / Calidad del spot (1-100)
  descripcion TEXT,
  ciudad TEXT DEFAULT 'Argentina',
  creado_en TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW())
);

-- 2. Habilitar Row Level Security (RLS) con políticas completas (CRUD) públicas para la PoC
ALTER TABLE skate_spots ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Lectura pública de spots"
  ON skate_spots FOR SELECT
  USING (true);

CREATE POLICY "Inserción pública de spots para PoC"
  ON skate_spots FOR INSERT
  WITH CHECK (true);

CREATE POLICY "Actualización pública de spots para PoC"
  ON skate_spots FOR UPDATE
  USING (true)
  WITH CHECK (true);

CREATE POLICY "Eliminación pública de spots para PoC"
  ON skate_spots FOR DELETE
  USING (true);

